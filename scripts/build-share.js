#!/usr/bin/env node
/*
 * Builds everything link-preview related from scripts/share-entries.js + site.config.json:
 *
 *   s/<slug>.html        one tiny page per shareable item (issue, chapters, lessons, brands).
 *                        It carries that item's preview tags (title, description, image) and
 *                        forwards readers to the real spot on the site, keeping utm_* tags.
 *                        This is how "Chapter III" can have its own Facebook preview.
 *   <!-- share:start --> preview tags injected into index.html, explainer.html, sponsor.html
 *   js/share-manifest.js  share URLs + story images for the on-page share menu
 *
 *   node scripts/build-share.js          (run after changing site.config.json or share-entries.js)
 * Images: scripts/render-share-images.js
 */
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, "site.config.json"), "utf8"));
const SITE = cfg.url.replace(/\/$/, "");
const entries = require("./share-entries")();
const esc = s => String(s ?? "").replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

function tags(e, url) {
  const title = e.slug === "issue-01" ? `${cfg.name}: ${e.title}` : `${e.title} · ${cfg.name}`;
  const desc = [e.desc, e.aside].filter(Boolean).join(" ");
  const img = `${SITE}/share/img/${e.slug}.jpg`;
  return [
    `<meta property="og:site_name" content="${esc(cfg.name)}">`,
    `<meta property="og:type" content="${e.slug.startsWith("brand-") ? "website" : "article"}">`,
    `<meta property="og:title" content="${esc(title)}">`,
    `<meta property="og:description" content="${esc(desc)}">`,
    `<meta property="og:url" content="${esc(url)}">`,
    `<meta property="og:image" content="${esc(img)}">`,
    `<meta property="og:image:width" content="1200">`, `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:alt" content="${esc(`${e.kicker}: ${e.title}`)}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${esc(title)}">`,
    `<meta name="twitter:description" content="${esc(desc)}">`,
    `<meta name="twitter:image" content="${esc(img)}">`,
    `<meta name="theme-color" content="#2B2826">`,
    `<link rel="icon" href="favicon.svg" type="image/svg+xml">`,
    `<link rel="apple-touch-icon" href="share/img/apple-touch-icon.png">`
  ].join("\n  ");
}

// 1) share pages
fs.mkdirSync(path.join(ROOT, "s"), { recursive: true });
for (const e of entries) {
  const url = `${SITE}/s/${e.slug}.html`;
  const [tpath, thash = ""] = e.target.split("#");
  fs.writeFileSync(path.join(ROOT, "s", `${e.slug}.html`), `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex, follow">
  <title>${esc(e.title)} · ${esc(cfg.name)}</title>
  <meta name="description" content="${esc(e.desc)}">
  <link rel="canonical" href="${esc(url)}">
  ${tags(e, url).replace(/href="(favicon\.svg|share\/)/g, 'href="../$1')}
  <script>
    // forward to the real page, keeping utm_* and other query params, then the #section
    var t = "../${tpath}", q = location.search, tq = t.indexOf("?") > -1;
    location.replace(t + (q ? (tq ? "&" + q.slice(1) : q) : "") + "${thash ? "#" + thash : ""}");
  </script>
  <noscript><meta http-equiv="refresh" content="0; url=../${esc(e.target)}"></noscript>
  <style>body{background:#2B2826;color:#F6EFE4;font:16px Georgia,serif;display:grid;place-items:center;min-height:100vh;margin:0}a{color:#F2A27C}</style>
</head>
<body><p>Opening <a href="../${esc(e.target)}">${esc(e.title)}</a>…</p></body>
</html>
`);
}

// 2) preview tags on the main pages (between markers, so re-running replaces them)
for (const e of entries.filter(e => e.page)) {
  const file = path.join(ROOT, e.page);
  let html = fs.readFileSync(file, "utf8");
  const block = `<!-- share:start (generated by scripts/build-share.js) -->\n  ${tags(e, `${SITE}/${e.page === "index.html" ? "" : e.page}`)}\n  <!-- share:end -->`;
  html = /<!-- share:start[\s\S]*?share:end -->/.test(html)
    ? html.replace(/<!-- share:start[\s\S]*?share:end -->/, block)
    : html.replace(/(\s*)<link rel="preconnect"/, `\n  ${block}$1<link rel="preconnect"`);
  fs.writeFileSync(file, html);
}

// 3) manifest for the on-page share menu
const manifest = { site: SITE, campaign: cfg.campaign, items: Object.fromEntries(entries.map(e => [e.slug, { title: e.title, story: `share/img/${e.slug}-story.jpg`, image: `share/img/${e.slug}.jpg` }])) };
fs.writeFileSync(path.join(ROOT, "js/share-manifest.js"), `/* generated by scripts/build-share.js */\nwindow.TT_SHARE_MANIFEST = ${JSON.stringify(manifest, null, 1)};\n`);

// 4) favicon
fs.writeFileSync(path.join(ROOT, "favicon.svg"), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="12" fill="#2B2826"/><text x="31" y="45" text-anchor="middle" font-family="Montserrat, Arial Black, sans-serif" font-weight="900" font-style="italic" font-size="36" letter-spacing="-3" fill="#F6EFE4">TT</text><rect x="12" y="52" width="40" height="5" rx="2" fill="#E2581C"/></svg>\n`);

console.log(`share: ${entries.length} share pages in s/, tags on ${entries.filter(e => e.page).map(e => e.page).join(", ")}, manifest written. Site URL: ${SITE}`);
